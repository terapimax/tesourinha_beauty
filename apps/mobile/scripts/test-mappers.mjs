assert.deepEqual(fromStartsAt('2026-12-01T17:00:00.000Z'), {date:'2026-12-01', time:'14:00'});
assert.deepEqual(fromStartsAt('2026-12-02T01:30:00Z'), {date:'2026-12-01', time:'22:30'});
assert.equal(weekdayOf('2026-12-01'), 2);
